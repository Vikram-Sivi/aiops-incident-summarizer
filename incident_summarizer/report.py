"""Render the analysis as a Markdown RCA draft."""
from __future__ import annotations


def render_markdown(analysis: dict, ctx: dict, source: str) -> str:
    lines = [
        f"# Incident summary (DRAFT): {ctx['service']} / {ctx['environment']}",
        "",
        f"_Generated by: {source}. Review and edit before sharing; this is a draft, not a final RCA._",
        "",
        "## Summary",
        analysis.get("summary", "n/a"),
        "",
        "## Impact",
        analysis.get("impact", "n/a"),
        "",
        "## Timeline",
    ]
    for item in analysis.get("timeline", []):
        lines.append(f"- **{item.get('time', 'unknown')}**: {item.get('event', '')}")
    lines += ["", "## Probable causes"]
    for c in analysis.get("probable_causes", []):
        lines.append(f"- **{c.get('cause', '')}** (confidence: {c.get('confidence', 'n/a')})")
        for ev in c.get("evidence", []):
            lines.append(f"  - evidence: {ev}")
    lines += ["", "## Recommended actions"]
    lines += [f"- {a}" for a in analysis.get("recommended_actions", [])]
    lines += ["", "## Open questions"]
    lines += [f"- {q}" for q in analysis.get("open_questions", [])]
    lines += ["", "## Top log patterns"]
    for c in ctx["log_clusters"][:5]:
        lines.append(f"- `{c['pattern']}` x{c['count']}")
    return "\n".join(lines) + "\n"
